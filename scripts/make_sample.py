"""Generates a SVAMITVA-style sample village (GeoJSON) + seed SQL.
Run from the project root: python3 scripts/make_sample.py
"""
import json, math, random

random.seed(7)
LON0, LAT0 = 75.8577, 22.7196  # sample centre (fictional village near Indore)
M_LAT = 111_320.0
M_LON = 111_320.0 * math.cos(math.radians(LAT0))
VID = "00000000-0000-0000-0000-000000000001"


def ll(x, y):
    return [round(LON0 + x / M_LON, 7), round(LAT0 + y / M_LAT, 7)]


feats = []
# existing roads: main street E-W plus lanes
roads = [
    ("main", "CC", 5.5, [(-150, 0), (-60, 4), (0, 0), (70, -5), (150, 0)]),
    ("lane", "WBM", 3.5, [(0, 0), (2, 60), (0, 120)]),
    ("lane", "Gravel", 3.0, [(0, 0), (-3, -60), (0, -110)]),
    ("lane", "Gravel", 3.0, [(-60, 4), (-62, 70)]),
    ("lane", "WBM", 3.5, [(70, -5), (72, -70)]),
]
for i, (kind, typ, w, pts) in enumerate(roads):
    feats.append({
        "type": "Feature",
        "properties": {"kind": "road", "road_type": typ, "width_m": w, "is_existing": True, "name": f"{kind}-{i}"},
        "geometry": {"type": "LineString", "coordinates": [ll(*p) for p in pts]},
    })


def block(cx, cy, w, d, rot=0.0):
    c, s = math.cos(rot), math.sin(rot)
    pts = [(-w / 2, -d / 2), (w / 2, -d / 2), (w / 2, d / 2), (-w / 2, d / 2), (-w / 2, -d / 2)]
    return [ll(cx + x * c - y * s, cy + x * s + y * c) for x, y in pts]


def along(pts, t):
    segs = list(zip(pts[:-1], pts[1:]))
    lens = [math.dist(a, b) for a, b in segs]
    d = t * sum(lens)
    for (a, b), l in zip(segs, lens):
        if d <= l:
            f = d / l
            return (a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f), math.atan2(b[1] - a[1], b[0] - a[0])
        d -= l
    return segs[-1][1], 0


roofs = ["RCC", "RCC", "Tiled", "Tin", "Thatch"]
for _, _, w, pts in roads:
    length = sum(math.dist(a, b) for a, b in zip(pts[:-1], pts[1:]))
    count = int(length / 14)
    for k in range(count):
        for side in (-1, 1):
            if random.random() < 0.22:
                continue
            (px, py), ang = along(pts, (k + 0.5) / count)
            off = w / 2 + 6 + random.uniform(0, 5)
            cx = px - math.sin(ang) * off * side
            cy = py + math.cos(ang) * off * side
            bw, bd = random.uniform(6, 10), random.uniform(5, 8)
            floors = random.choice([1, 1, 1, 2])
            feats.append({
                "type": "Feature",
                "properties": {"kind": "building", "height_m": round(3.0 * floors + random.uniform(0, 0.6), 1),
                               "floors": floors, "roof_type": random.choice(roofs)},
                "geometry": {"type": "Polygon", "coordinates": [block(cx, cy, bw, bd, ang)]},
            })

# a hamlet with no road access (south-east) -> used for inclusion scoring
for i in range(7):
    cx = 95 + (i % 4) * 11 + random.uniform(-2, 2)
    cy = -95 - (i // 4) * 12 + random.uniform(-2, 2)
    feats.append({
        "type": "Feature",
        "properties": {"kind": "building", "height_m": 3.2, "floors": 1,
                       "roof_type": random.choice(["Tiled", "Thatch"]), "hamlet": "Bhil Tola"},
        "geometry": {"type": "Polygon", "coordinates": [block(cx, cy, 6, 5, random.uniform(-0.3, 0.3))]},
    })

fc = {
    "type": "FeatureCollection",
    "name": "sample-village",
    "properties": {"name": "Rampura (sample)", "gram_panchayat": "Rampura", "district": "Indore",
                   "state": "Madhya Pradesh", "centroid": [LON0, LAT0]},
    "features": feats,
}
with open("src/data/sample-village.geojson", "w") as fh:
    json.dump(fc, fh)
print("features:", len(feats))


def wkt(coords):
    return ", ".join(f"{x} {y}" for x, y in coords)


out = ["-- Auto-generated by scripts/make_sample.py",
       "insert into villages (id,name,gram_panchayat,district,state,centroid) values",
       f"  ('{VID}','Rampura (sample)','Rampura','Indore','Madhya Pradesh',"
       f" ST_SetSRID(ST_MakePoint({LON0},{LAT0}),4326)) on conflict do nothing;"]
for f in feats:
    p, g = f["properties"], f["geometry"]
    if p["kind"] == "road":
        out.append(
            "insert into roads (village_id,geometry,road_type,width_m,is_existing) values "
            f"('{VID}', ST_GeomFromText('LINESTRING({wkt(g['coordinates'])})',4326), "
            f"'{p['road_type']}', {p['width_m']}, true);")
    else:
        out.append(
            "insert into buildings (village_id,footprint,height_m,roof_type,floors) values "
            f"('{VID}', ST_GeomFromText('POLYGON(({wkt(g['coordinates'][0])}))',4326), "
            f"{p['height_m']}, '{p['roof_type']}', {p['floors']});")
with open("supabase/seed_village.sql", "w") as fh:
    fh.write("\n".join(out) + "\n")
